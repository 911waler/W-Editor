import { readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/u

export const RELEASE_VERSIONS_PATH = 'release/versions.json'
export const EDITOR_WEB_RELEASE_VERSION_SOURCE_PATH = 'packages/editor-web/src/releaseVersions.generated.ts'

const EDITOR_WEB_RELEASE_VERSION_KEYS = Object.freeze([
  'webApiVersion',
  'webSchemaVersion',
  'hostContractsVersion',
  'minimumHostAdapterVersion',
])

function requireSemVer(value, key) {
  if (typeof value !== 'string' || !SEMVER.test(value)) throw new Error(`Release version ${key} must be a SemVer string.`)
  return value
}

function requireInteger(value, key) {
  if (!Number.isInteger(value) || value < 1) throw new Error(`Release version ${key} must be a positive integer.`)
  return value
}

export function readReleaseVersions(repositoryRoot = resolve(import.meta.dirname, '..')) {
  const path = join(repositoryRoot, RELEASE_VERSIONS_PATH)
  const source = JSON.parse(readFileSync(path, 'utf8'))
  const versions = {
    productVersion: requireSemVer(source.productVersion, 'productVersion'),
    webApiVersion: requireSemVer(source.webApiVersion, 'webApiVersion'),
    webSchemaVersion: requireSemVer(source.webSchemaVersion, 'webSchemaVersion'),
    hostContractsVersion: requireSemVer(source.hostContractsVersion, 'hostContractsVersion'),
    minimumHostAdapterVersion: requireSemVer(source.minimumHostAdapterVersion, 'minimumHostAdapterVersion'),
    markdownDialectVersion: requireSemVer(source.markdownDialectVersion, 'markdownDialectVersion'),
    databaseSchemaVersion: requireInteger(source.databaseSchemaVersion, 'databaseSchemaVersion'),
    dataRootSchemaVersion: requireInteger(source.dataRootSchemaVersion, 'dataRootSchemaVersion'),
    settingsSchemaVersion: requireInteger(source.settingsSchemaVersion, 'settingsSchemaVersion'),
    manifestVersion: requireSemVer(source.manifestVersion, 'manifestVersion'),
  }
  return Object.freeze(versions)
}

export function renderEditorWebReleaseVersionSource(versions) {
  const fields = EDITOR_WEB_RELEASE_VERSION_KEYS
    .map((key) => `  ${key}: '${versions[key]}',`)
    .join('\n')
  return `// Generated by scripts/generate-release-version-sources.mjs from ${RELEASE_VERSIONS_PATH}. Do not edit.\nexport const RELEASE_VERSIONS = Object.freeze({\n${fields}\n} as const)\n`
}

export function desktopArtifactFileNames(versions) {
  return Object.freeze({
    nsis: `W-Editor Desktop_${versions.productVersion}_x64-setup.exe`,
    msi: `W-Editor Desktop_${versions.productVersion}_x64_en-US.msi`,
  })
}

export function desktopArtifactPaths(targetRoot, versions) {
  const names = desktopArtifactFileNames(versions)
  return Object.freeze({
    nsis: join(targetRoot, 'debug', 'bundle', 'nsis', names.nsis),
    msi: join(targetRoot, 'debug', 'bundle', 'msi', names.msi),
  })
}
